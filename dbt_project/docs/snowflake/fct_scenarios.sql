    SELECT LISTING_ID
    FROM (
        SELECT
            LISTING_ID,
            ROW_NUMBER() OVER (
                PARTITION BY LISTING_ID
                ORDER BY LISTING_ID
            ) AS RN
        FROM RAW_DB.RAW_SCHEMA.RAW_REVIEWS
